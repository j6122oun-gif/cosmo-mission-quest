export const planetById = (id) => PLANETS.find((p) => p.id === id) || null;

export const TOTAL_TARGETS = PLANETS.reduce((sum, p) => sum + p.targets.length, 0);

export function planetMaxPoints(planet) {
  return planet.targets.reduce((sum, t) => sum + t.points, 0);
}

export function sumLoadout(ids = []) {
  return ids.reduce(
    (acc, id) => {
      const item = equipmentById[id];
      if (!item) return acc;
      return {
        budget: acc.budget + item.cost,
        mass: acc.mass + item.mass,
        power: acc.power + item.power,
      };
    },
    { budget: 0, mass: 0, power: 0 },
  );
}

export function countFound(discoveries = {}) {
  return Object.values(discoveries).reduce((sum, list) => sum + (list?.length || 0), 0);
}